// 01_basics.go —— 认识指针：& 取地址、* 解引用、nil 指针
//
// 先打个比喻（前端完全没有对应概念，请认真看这段铺垫）：
//
//	内存 = 一栋公寓楼
//	每个变量 = 楼里的一间房间
//	地址（指针）= 房间的门牌号
//
//	&x   = 查出 x 的门牌号（取地址）
//	*p   = 拿着门牌号 p 进去，看房间里的人（解引用）
//
// 前端对照：JS 里你永远接触不到"地址"，
//
//	但你已经用过它的影子 —— 对象引用（02、03 节会讲透）
package main

import "fmt"

// demoBasics 演示 & 和 * 的基本用法 + nil 指针
func demoBasics() {
	fmt.Println("========== 01 认识指针 ==========")


	// ---------- 1. & 取地址：p 的类型是 *int（int 的指针） ----------
	x := 10
	p := &x // p 存的是 x 的内存地址（门牌号）
	fmt.Println("x =", x)
	fmt.Println("p =", p) // 形如 0xc0000123a0，每次运行可能不同
	fmt.Printf("p 的类型: %T\n", p) // *int → 读作"int 的指针"


	// ---------- 2. * 解引用：通过 p 拿 x 的值、改 x 的值 ----------
	fmt.Println("*p =", *p) // 10 —— 按门牌号找过去，就是 x 的值

	*p = 99 // 通过指针改值：*p = 新值 → x 也跟着变（改的是同一间房间）
	fmt.Println("执行 *p = 99 后：x =", x) // 99 ← x 被改了！

	//? 思考：为什么不直接写 x，非要绕一圈 p = &x 再用 *p？
	//? 答：自己一个人的时候确实不用绕 —— 指针的价值在于把门牌号【给别人】，
	//?     别人拿着它就能改你的房间（02、03 节讲）。到时候就没法直接写 x 了


	// ---------- 3. 零值：指针的零值是 nil ----------
	var q *int // 只声明不赋值 → q 是 nil（手里没有门牌号）
	fmt.Println("\nq == nil ?", q == nil) // true

	//! 对 nil 指针解引用 → 直接 panic 崩溃！
	//! fmt.Println(*q)  // ❌ panic: runtime error: invalid memory address
	fmt.Println("🔑 nil 指针 = 空门牌号，拿着空门牌号找人 → 程序崩溃")
	fmt.Println("   前端对照：类似 JS 的 null，但 JS 报个 TypeError 还能继续，Go 直接 panic")
}
