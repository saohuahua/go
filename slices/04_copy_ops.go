// 04_copy_ops.go —— 想要"独立的副本"用 copy；还有删除、清空
//
// 02 节说了：截取是共享内存（视图）。如果你真的需要一份独立数据
// （比如排序、修改时不想影响原切片），就用内置函数 copy。
package main

import "fmt"

// demoCopy 演示 copy 深拷贝、删除元素、清空切片
func demoCopy() {
	fmt.Println("========== 04 copy 拷贝 / 删除 / 清空 ==========")

	// ---------- 1. copy：复制出真正独立的一份 ----------
	a := []int{1, 2, 3}
	b := make([]int, len(a)) // 目标切片必须有足够的长度
	n := copy(b, a)          // 把 a 复制给 b，返回复制成功的个数
	fmt.Println("a =", a, " b =", b, " 复制个数 =", n)

	b[0] = 100 // 改 b 不影响 a
	fmt.Println("改 b[0] = 100 后，a 仍然是", a) // [1 2 3]

	// 补充：copy 是"能复制多少就复制多少"
	// 如果目标太短，就只复制目标长度那么多个元素
	short := make([]int, 2)
	copy(short, a) // 目标只有 2 个位置，所以只复制 2 个
	fmt.Println("目标长度只有 2，复制结果 short =", short) // [1 2]

	// ---------- 2. 删除中间的元素（Go 没有内置 delete） ----------
	s := []int{10, 20, 30, 40}
	idx := 2
	// 思路：把"下标 idx 之前" + "idx 之后"两段拼起来
	// s[:2] = [10 20]，s[3:] = [40] → 拼成 [10 20 40]
	s = append(s[:idx], s[idx+1:]...)
	fmt.Println("\n删除下标 2 后 s =", s) // [10 20 40]

	// ⚠️ 注意：上面这种写法会改动底层数组（原本下标 3 的 40 被覆盖到下标 2）
	// 如果 s 是别处截取的"视图"，原切片也会跟着变 → 用 02 节的三索引截取可以防这个

	// ---------- 3. 清空切片 ----------
	s = s[:0] // 长度变 0，但容量还在（底层数组仍占着内存，可复用）
	fmt.Println("\ns = s[:0] 后：len =", len(s), " cap =", cap(s), " s =", s)

	s = nil // 彻底清空，底层数组可被垃圾回收
	fmt.Println("s = nil 后：s == nil ?", s == nil)

	// 区分两个概念：
	//   nil 切片（s == nil）     → 没分配任何底层数组
	//   空切片（s 但 len 为 0）   → 有底层数组，只是里面没元素
	// 日常判断"有没有元素"用 len(s) == 0，不要用 s == nil
}
