// 03_append.go —— append 追加元素 + 扩容机制（面试必问！）
//
// 你的学习路线里，面试高频清单明确列出了「切片扩容机制」。
// 这一节请重点看三件事：什么时候扩容、怎么扩、为什么 append 必须重新赋值。
package main

import "fmt"

// demoAppend 演示 append 用法与扩容机制
func demoAppend() {
	fmt.Println("========== 03 append 追加与扩容 ==========")

	// ---------- 1. append 基本用法 ----------
	// 语法：append(原切片, 新元素...) → 返回一个新切片
	s := []int{1, 2, 3}
	s = append(s, 4)               // 追加 1 个
	s = append(s, 5, 6, 7)         // 追加多个
	s = append(s, []int{8, 9}...)  // 追加整个切片（... 展开，类似 JS 的展开运算符）
	fmt.Println("s =", s) // [1 2 3 4 5 6 7 8 9]
	fmt.Println("📌 前端对照：append 就像 JS 的 push，")
	fmt.Println("   但必须把返回值赋回给原变量（原因见下面第 3 点）")

	// ---------- 2. 亲眼看看扩容 ----------
	fmt.Println("\n----- 观察扩容过程（初始容量 2）-----")
	s2 := make([]int, 0, 2) // 空切片，初始容量 2
	prevCap := cap(s2)
	for i := 1; i <= 10; i++ {
		s2 = append(s2, i)
		if cap(s2) != prevCap { // 容量变了 → 说明这次 append 触发了扩容
			fmt.Printf("  第 %d 次追加时扩容：容量 %d → %d\n", len(s2), prevCap, cap(s2))
			prevCap = cap(s2)
		}
	}

	// ---------- 3. 扩容的底层原理（面试重点） ----------
	// 当 len == cap，说明底层数组满了，append 会做三步：
	//   ① 申请一块更大的新内存（新的底层数组）
	//   ② 把旧元素全部拷贝过去
	//   ③ 让切片指向新数组，旧数组交给垃圾回收
	// 因为底层数组换了个位置，所以：
	//   ❌ 不接返回值：s 还指向旧数组，追加的数据等于"丢了"
	//   ✅ 必须写：s = append(s, x)，把返回的新切片接住

	// 扩容的倍率（Go 1.18 之后）：
	//   原容量 < 256 个 → 直接翻倍（×2）
	//   原容量 ≥ 256 个 → 约 ×1.25 缓慢增长（避免大切片浪费过多内存）
	//   （实际分配还会按内存对齐微调，所以容量不一定是精确的 2 倍）
	fmt.Println("\n🔑 扩容口诀：小于 256 翻倍，大于 256 约加四分之一")
	fmt.Println("   为什么要缓涨？容量越大，翻倍浪费的内存越多，1.25 倍更省")
}
