// 01_basics.go —— 数组 vs 切片 + 三种创建方式 + len/cap
//
// 先打个比喻，方便你从 JS 思维迁移过来：
//   数组 = 一个【固定大小】的盒子，装 3 个就永远 3 个
//   切片 = 一个【可以自动变大】的盒子，想装多少装多少
//
// 你来自前端，对 JS 数组很熟，但要注意一个关键区别：
//   JS 只有一种数组（动态的，像 Go 的切片）
//   Go 分【数组】和【切片】两种 —— 日常开发 99% 用的都是【切片】
package main

import "fmt"

// demoBasics 演示：数组 vs 切片、三种创建方式、len/cap 的含义
func demoBasics() {
	fmt.Println("========== 01 数组 vs 切片 ==========")

	// ---------- 1. 数组：长度写死 ----------
	// 注意写法：[] 里面有数字 [3]，长度就是 3，改不了
	arr := [3]int{1, 2, 3}
	fmt.Println("数组 arr =", arr, "长度 =", len(arr))
	// arr[3] = 4  // ❌ 取消注释会编译报错：数组越界（没有下标 3）

	// ---------- 2. 切片：长度可变 ----------
	// 写法上只是少了长度数字，这才是你熟悉的"动态数组"
	var sl []int         // 声明一个切片（注意：[] 里没有数字）
	sl = []int{1, 2, 3}  // 用字面量初始化
	fmt.Println("切片 sl =", sl, "长度 =", len(sl))

	// ---------- 3. 创建切片的三种方式 ----------
	// 方式一：字面量（最常用）
	s1 := []int{10, 20, 30}
	fmt.Println("\n方式一 字面量   s1 =", s1)

	// 方式二：make，可以同时指定长度和容量
	// 语法：make([]类型, 长度, 容量)，容量可以省略（省略时 = 长度）
	s2 := make([]int, 3)    // 长度 3，元素全部是零值 0
	s3 := make([]int, 3, 5) // 长度 3，容量 5
	fmt.Println("方式二 make    s2 =", s2, " len =", len(s2), " cap =", cap(s2))
	fmt.Println("方式二 make    s3 =", s3, " len =", len(s3), " cap =", cap(s3))

	// 方式三：从一个已有的切片/数组"截取"出来（下一节细讲，先眼熟）
	base := []int{1, 2, 3, 4, 5}
	s4 := base[1:3] // 取下标 1、2（左闭右开，不含下标 3）
	fmt.Println("方式三 截取     base[1:3] =", s4)

	// ---------- 4. len 和 cap：切片的两个核心属性 ----------
	// len（长度）：你现在能读到、能写的元素个数
	// cap（容量）：底层数组总共能装多少元素
	// 当 len 撞到 cap，再 append 就要扩容（见 03 节）
	fmt.Println("\n🔑 一句话记住：cap 是「车位」，len 是「已停的车」,")
	fmt.Println("   车位不够时 Go 会换一个更大的停车场（扩容）")
}
