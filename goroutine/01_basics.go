// 01_basics.go —— 启动 goroutine：Go 最迷人的地方，也是最容易翻车的地方
//
// 先记一句最关键的对照（后面所有内容都建立在它上面）：
//
//	Promise 是"排队等"：还在同一根线程上，本质还是一个人干活
//	goroutine 是"另开一条跑道"：真的同时有好几件事在跑
//
// 看到 go 关键字，就记住一句话：从这一刻起，又多了一条独立的跑道。
package main

import (
	"fmt"
	"time"
)

// demoBasics 演示 go 关键字启动协程 + "主函数退出 = 协程全没"的大坑
func demoBasics() {
	fmt.Println("========== 01 启动 goroutine ==========")

	// go 函数() = 另开一条跑道去跑函数，然后立刻返回，不等它跑完
	go fmt.Println("① 我是协程里的输出")
	fmt.Println("② 我是主函数的输出")

	//! 最经典的坑：① 可能根本没打印！
	//! 原因：主函数跑完 return 的瞬间，程序就结束了，所有协程被一起杀掉
	// 多跑几遍体会：有时 ① 先打印，有时 ② 先打印，有时 ① 直接消失
	// → 这就是"并发的不确定性"，这一章你会反复见到它

	// 笨办法：time.Sleep 睡一下，让出时间给协程跑
	// 缺点：睡多久全凭猜 —— 睡少了没跑完，睡多了浪费时间
	go fmt.Println("③ 睡一觉之后：这次能看到我了")
	time.Sleep(time.Millisecond)
	fmt.Println("④ main 睡了一毫秒，③ 确实打印出来了")

	// 举一反三：开 10 个协程，每个打印自己的编号
	// 结论提前给：顺序每次都不固定 —— 谁先跑完全看调度心情
	fmt.Println("\n⑤ 开 10 个协程，打印顺序每次都不相同：")
	for i := 0; i < 10; i++ {
		go fmt.Println("协程", i) // 把 i 当参数直接传，不经过闭包
		// go func() { fmt.Println(i) }() 
	}
	time.Sleep(10 * time.Millisecond)
	// 融会贯通：map/03 里 range 遍历顺序随机，这里协程执行顺序也随机
	// → Go 的两个"不保证顺序"是同一个道理：别指望并发下的顺序

	//? 思考：上面写 go fmt.Println("协程", i) 为什么不写 go func(){ fmt.Println(i) }()？
	//? 答：前者是把 i"那一刻的值"当参数传进去（快照）；
	//?     后者是闭包捕获变量（引用）。Go < 1.22 时循环里闭包捕获会踩坑
	//?     —— 协程真跑时 i 可能已变到最后一个值，全打印同一个数；
	//?     Go 1.22+ 已修复（每轮一个独立 i）。但"传值=快照 / 捕获=引用"
	//?     的语义呼应 pointers/02 的传值 vs 传指针，面试常考，两种写法都要会看

	//* 眼见为实：Go 1.22 只修了"循环变量"这个特例，"捕获=引用"的语义还在
	//   循环外照样能看出区别 —— 同一条协程里，传参和闭包看到两个不同的数
	fmt.Println("\n⑥ 传值 vs 闭包捕获（结果固定，多跑几遍也一样）：")
	x := 1
	release := make(chan struct{}) // 借 02 的 channel 当"闸门"：先堵住，改完再放行
	go func(v int) {
		<-release // 堵在这，等 x 改成 999 才放行 —— 保证"先改、后看"
		fmt.Println("   传参（go 那一刻复印）：v =", v, "   闭包（跑的那一刻开盒子）：x =", x)
	}(x)
	x = 999 // 先改盒子再放行：传参早已复印好不受影响，闭包看到的是最新值
	close(release)
	time.Sleep(time.Millisecond) // 主函数退出 = 协程全没（本节最大的坑），睡一觉等它打印完

	fmt.Println("\n🔑 本章主线：主函数不会等协程，协程也不会等你")
	fmt.Println("   等协程的正规武器 = channel（下一节）和 WaitGroup（04 节）")
}
