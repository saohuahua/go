// 02_channel.go —— channel：协程之间通信的"管道"
//
// 前端对照（先记这句）：
//
//	channel ≈ 一根水管 / 一条消息队列：一端灌水，另一端接水
//	JS 里最接近的是 postMessage / 任务队列
//
// 但 Go 的 channel 有个 JS 没有的硬规矩：无缓冲时，收发双方必须"同时在场"。
package main

import (
	"fmt"
)

// demoChannel 演示 channel 的收发 + 无缓冲 channel 的"同步阻塞"
func demoChannel() {
	fmt.Println("========== 02 channel：协程通信 ==========")

	// 造一根"装 int 的水管"：ch := make(chan int)
	//   发送：ch <- 42    箭头指向水管 = 把 42 灌进去
	//   接收：v := <-ch   箭头从水管出来 = 接出一桶水给 v
	// 注意 <- 的方向就是数据流动的方向，永远别记反
	ch := make(chan int)

	// 开一条协程往水管里灌水，主函数在这头接水：
	go func() {
		ch <- 42 // 发送
	}()
	v := <-ch // 接收
	fmt.Println("从 channel 里收到 =", v)

	// 上面能跑通，靠的就是无缓冲 channel 的"同步阻塞"：
	//   发送方：没人来接收 → 我堵在这，直到有人接
	//   接收方：没人来发送 → 我堵在这，直到有人发
	// → 收发双方像"隔空击掌"，必须同时到场，这就是"同步"

	//* 前端对照：postMessage 是异步的（发完就走，对方晚点收）
	//           Go 的无缓冲 channel 是同步的（发完必须等对方收走）
	// 这不是 bug，是特性：它天然保证"我发完 → 你收到"的先后顺序

	//! 死锁大坑：只发不收 / 只收不发 → 双方都堵死 → panic: deadlock
	//! 解开下面三行试一次（会直接崩溃）：
	//! ch2 := make(chan int)
	//! ch2 <- 1 // 发送后永远没人来收 → 卡死
	//! _ = ch2

	// 融会贯通：channel 和 map（map/02）一样是"引用类型"
	// 上面的协程和 main 用的是同一个 channel，不是拷贝 —— 所以才能互相收发
	// 传参同理：把 channel 传给函数，函数里发/收的就是同一个管道

	//? 思考：上面那个 goroutine 和主函数，谁先执行？
	//? 答：不保证！但不管谁先到，发送和接收总"碰得上头"——
	//?     先到的一方会被阻塞，一直等到另一方出现（这就是同步的含义）

	fmt.Println("\n🔑 一句话：无缓冲 channel = 同步 = 收发必须成双成对")
}
